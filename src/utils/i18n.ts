export const LANGUAGE_STORAGE_KEY = 'sis_mob_sumbe_lang';

export function getStoredLanguage(): SupportedLanguage {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY) as SupportedLanguage;
    if (saved && ['pt', 'en', 'fr', 'umb'].includes(saved)) {
      return saved;
    }
  } catch (e) {
    // fallback
  }
  return 'pt';
}

export function setStoredLanguage(lang: SupportedLanguage) {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch (e) {
    // ignore
  }
}

export const getSavedLanguage = getStoredLanguage;
export const saveLanguage = setStoredLanguage;
