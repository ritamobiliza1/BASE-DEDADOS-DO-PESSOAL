export function loadAppState(): AppState {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (parsed && Array.isArray(parsed.mobs) && parsed.mobs.length > 0) {
        // Garantir retrocompatibilidade, limpeza de valores e normalização de coordenações (ex: CASA-BRANCA)
        parsed.mobs.forEach((p: any) => { delete p.valor; delete p.total; p.coord = normalizeCoordName(p.coord); });
        parsed.sups?.forEach((p: any) => { delete p.valor; delete p.total; p.coord = normalizeCoordName(p.coord); });
        parsed.motos?.forEach((p: any) => { delete p.valor; delete p.total; p.coord = normalizeCoordName(p.coord); });
        parsed.recs?.forEach((r: any) => { delete r.valor; r.coord = normalizeCoordName(r.coord); });
        return parsed;
      }
    }
  } catch (err) {
    console.warn('Erro ao carregar dados do localStorage, inicializando padrão:', err);
  }

  const initial = getInitialState();
  saveAppState(initial);
  return initial;
}

export function saveAppState(state: AppState) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(state));
  } catch (err) {
    console.error('Falha ao gravar estado localmente:', err);
  }
}

export function logHistory(state: AppState, action: string, person: string, details?: string): AppState {
  const newItem: HistoryItem = {
    id: generateId(),
    at: new Date().toLocaleString('pt-AO'),
    action,
    person,
    details,
  };
  const updatedHistory = [newItem, ...(state.history || [])].slice(0, 300);
  const nextState = { ...state, history: updatedHistory };
  saveAppState(nextState);
  return nextState;
}

export function exportBackupJSON(state: AppState) {
  const cleanState = {
    ...state,
    exportedAt: new Date().toISOString(),
    system: 'Sistema de Mobilizadores · Sumbe PRO',
  };
  const blob = new Blob([JSON.stringify(cleanState, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Backup_Mobilizadores_Sumbe_Offline_${new Date().toISOString().slice(0, 10)}.json`;
  a.click();
  URL.revokeObjectURL(url);
}
